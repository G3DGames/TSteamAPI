def existing_guid(path):
    if os.path.exists(path):
        m = re.search(r"<ProjectGuid>(\{[0-9A-Fa-f-]+\})</ProjectGuid>", open(path, encoding="utf-8-sig").read())
        if m:
            return m.group(1)
    return "{" + str(uuid.uuid4()).upper() + "}"


# What the IDE's Project > Enable Skia adds to a .dproj (as it wrote it into
# VirtualGamepad.dproj): the SKIA define (Base) and Skia's library deployed
# next to the program - from $(BDS) unless SKIADIR names a separate Skia4Delphi.
# Projects with skia=True get them. The IDE ALSO writes
# "GlobalUseSkia := True;" into the .dpr: never kept - FmxSkiaCanvas switches
# Skia on only when TSAPI_FMX_CANVAS asks for it (docs/Proton.md).
SKIA_LIBS = {"Win32": ("$(BDS)\\bin\\sk4d.dll", "sk4d.dll", "0"),
             "Win64": ("$(BDS)\\bin64\\sk4d.dll", "sk4d.dll", "0"),
             "Linux64": ("$(BDS)\\binlinux64\\libsk4d.so", "libsk4d.so", "1")}


def skia_deploy(p, a):
    """Writes the Enable Skia DeployFile entries of project p with a()."""
    for pl, (bds_path, name, op) in SKIA_LIBS.items():
        if pl not in p["platforms"]:
            continue
        for cond, local in (("==", bds_path), ("!=", f"$(SKIADIR)\\Binary\\Shared\\{pl}\\{name}")):
            for cfg in ("Debug", "Release"):
                a(f"""                <DeployFile Condition="'$(SKIADIR)'{cond}''" Required="true" LocalName="{local}" Configuration="{cfg}" Class="Skia">""")
                a(f'                    <Platform Name="{pl}">')
                a('                        <RemoteDir>.\\</RemoteDir>')
                a(f'                        <Operation>{op}</Operation>')
                a(f'                        <RemoteName>{name}</RemoteName>')
                a('                        <Overwrite>true</Overwrite>')
                a('                    </Platform>')
                a('                </DeployFile>')


def dproj(p):
    path = os.path.join(ROOT, *p["dir"].split("\\"), p["name"] + ".dproj")
    guid = existing_guid(path)
    is_pkg = p["kind"] in ("runtime", "design")
    main = p["name"] + (".dpk" if is_pkg else ".dpr")
    apptype = "Package" if is_pkg else ("Console" if p["kind"] == "console" else "Application")
    L = []
    a = L.append
    a('<Project xmlns="http://schemas.microsoft.com/developer/msbuild/2003">')
    a('    <PropertyGroup>')
    a(f'        <ProjectGuid>{guid}</ProjectGuid>')
    a('        <ProjectVersion>20.5</ProjectVersion>')  # Delphi 13 (Studio 37.0)
    a(f'        <FrameworkType>{p["framework"]}</FrameworkType>')
    a(f'        <AppType>{apptype}</AppType>')
    a(f'        <MainSource>{main}</MainSource>')
    a('        <Base>True</Base>')
    a("        <Config Condition=\"'$(Config)'==''\">Debug</Config>")
    a(f"        <Platform Condition=\"'$(Platform)'==''\">{p['default']}</Platform>")
    a(f"        <ProjectName Condition=\"'$(ProjectName)'==''\">{p['name']}</ProjectName>")
    a('    </PropertyGroup>')
    a("    <PropertyGroup Condition=\"'$(Config)'=='Base' or '$(Base)'!=''\">")
    a('        <Base>true</Base>')
    a('    </PropertyGroup>')
    for pl in p["platforms"]:
        a(f"    <PropertyGroup Condition=\"('$(Platform)'=='{pl}' and '$(Base)'=='true') or '$(Base_{pl})'!=''\">")
        a(f'        <Base_{pl}>true</Base_{pl}>')
        a('        <CfgParent>Base</CfgParent>')
        a('        <Base>true</Base>')
        a('    </PropertyGroup>')
    for key, cfg in (("Cfg_1", "Debug"), ("Cfg_2", "Release")):
        a(f"    <PropertyGroup Condition=\"'$(Config)'=='{cfg}' or '$({key})'!=''\">")
        a(f'        <{key}>true</{key}>')
        a('        <CfgParent>Base</CfgParent>')
        a('        <Base>true</Base>')
        a('    </PropertyGroup>')
    a("    <PropertyGroup Condition=\"'$(Base)'!=''\">")
    a(f'        <SanitizedProjectName>{p["name"].replace(".", "_")}</SanitizedProjectName>')
    a(f'        <DCC_Namespace>{NS_BASE};$(DCC_Namespace)</DCC_Namespace>')
    a(f'        <DCC_UnitSearchPath>{p["search"]};$(DCC_UnitSearchPath)</DCC_UnitSearchPath>')
    a(f'        <DCC_IncludePath>{p["search"]};$(DCC_IncludePath)</DCC_IncludePath>')
    if p["kind"] == "runtime":
        # DCUs next to the .dcp, on the IDE's default Library path, so projects
        # (demos included) need no paths; Win32 is overridden in Base_Win32
        a('        <DCC_DcuOutput>$(BDSCOMMONDIR)\\Dcp\\$(Platform)</DCC_DcuOutput>')
    else:
        a('        <DCC_DcuOutput>.\\$(Platform)\\$(Config)\\dcu</DCC_DcuOutput>')
    if is_pkg:
        # No DCC_BplOutput / DCC_DcpOutput: Delphi's defaults ($(BDSCOMMONDIR)\\Bpl and
        # \\Dcp per platform) are on the IDE's PATH and library path, so the design
        # package finds SteamworksFMX.dcp and the IDE can load SteamworksFMX.bpl.
        a('        <GenDll>true</GenDll>')
        a('        <GenPackage>true</GenPackage>')
        a(f'        <DCC_Description>{p["description"]}</DCC_Description>')
        if p["kind"] == "runtime":
            a('        <RuntimeOnlyPackage>true</RuntimeOnlyPackage>')
        else:
            a('        <DesignOnlyPackage>true</DesignOnlyPackage>')
    else:
        a('        <DCC_ExeOutput>.\\$(Platform)\\$(Config)</DCC_ExeOutput>')
    if p.get("skia"):
        a('        <DCC_Define>SKIA;$(DCC_Define)</DCC_Define>')
    a('        <DCC_E>false</DCC_E>')
    a('        <DCC_N>false</DCC_N>')
    a('        <DCC_S>false</DCC_S>')
    a('        <DCC_F>false</DCC_F>')
    a('        <DCC_K>false</DCC_K>')
    a('    </PropertyGroup>')
    for pl in p["platforms"]:
        a(f"    <PropertyGroup Condition=\"'$(Base_{pl})'!=''\">")
        ns = NS_PLAT[pl] + (";" + NS_VCL if p["framework"] == "VCL" else "")
        a(f'        <DCC_Namespace>{ns};$(DCC_Namespace)</DCC_Namespace>')
        if p["kind"] == "runtime" and pl == "Win32":
            # Win32's Dcp folder has no platform sub-folder (see the Base group)
            a('        <DCC_DcuOutput>$(BDSCOMMONDIR)\\Dcp</DCC_DcuOutput>')
        if pl.startswith("OSX") and p["kind"] in ("app", "console"):
            # Without bundle keys the IDE writes an EMPTY Info.plist and PAServer's
            # 'plutil -convert binary1' fails (E0264) - seen 2026-10-30, OSXARM64.
            a('        <VerInfo_IncludeVerInfo>true</VerInfo_IncludeVerInfo>')
            a(f'        <VerInfo_Keys>{MAC_KEYS}</VerInfo_Keys>')
        if (p.get("redist") or p.get("files")) and pl.startswith("Win"):
            src = f"$(PROJECTDIR)\\..\\..\\redistributable_bin\\{REDIST[pl]}{DLL[pl]}"
            # The IDE re-saves the event as ONE line joined with '&&', and cmd makes
            # everything after an 'if' part of its body - so no 'if' here: a failed
            # copy runs the bracketed error. The brackets hold only literal text (no
            # macro paths, which may contain ')'). A missing redistributable FAILS
            # the build: exit code 1, not ignored.
            msg = (f'could not copy {DLL[pl]} from redistributable_bin\\{REDIST[pl]} - if it is missing, '
                   f'copy redistributable_bin from the Steamworks SDK 1.65 into the repository root, '
                   f'then run tools\\check_redist.py')
            steps = []
            if p.get("redist"):
                steps.append(f'echo Steamworks post-build: $(Platform) $(Config), copying {DLL[pl]} to $(OUTPUTDIR)\r\n'
                             f'copy /Y "{src}" "$(OUTPUTDIR)" || (echo ERROR: {msg} & exit /b 1)')
            for f in p.get("files", []):
                fn = f.split("\\")[-1]
                steps.append(f'echo Steamworks post-build: copying {fn} to $(OUTPUTDIR)\r\n'
                             f'copy /Y "$(PROJECTDIR)\\{f}" "$(OUTPUTDIR)" || '
                             f'(echo ERROR: could not copy {fn} next to the executable & exit /b 1)')
            cmd = "\r\n".join(steps)
            a('        <PostBuildEvent><![CDATA[' + cmd + ']]></PostBuildEvent>')
            a('        <PostBuildEventIgnoreExitCode>false</PostBuildEventIgnoreExitCode>')
        a('    </PropertyGroup>')
    a("    <PropertyGroup Condition=\"'$(Cfg_1)'!=''\">")
    a('        <DCC_Define>DEBUG;$(DCC_Define)</DCC_Define>')
    a('        <DCC_DebugDCUs>true</DCC_DebugDCUs>')
    a('        <DCC_Optimize>false</DCC_Optimize>')
    a('        <DCC_GenerateStackFrames>true</DCC_GenerateStackFrames>')
    a('        <DCC_DebugInfoInExe>true</DCC_DebugInfoInExe>')
    a('        <DCC_RemoteDebug>true</DCC_RemoteDebug>')
    a('    </PropertyGroup>')
    a("    <PropertyGroup Condition=\"'$(Cfg_2)'!=''\">")
    a('        <DCC_LocalDebugSymbols>false</DCC_LocalDebugSymbols>')
    a('        <DCC_Define>RELEASE;$(DCC_Define)</DCC_Define>')
    a('        <DCC_SymbolReferenceInfo>0</DCC_SymbolReferenceInfo>')
    a('        <DCC_DebugInformation>0</DCC_DebugInformation>')
    a('    </PropertyGroup>')
    a('    <ItemGroup>')
    a('        <DelphiCompile Include="$(MainSource)">')
    a('            <MainSource>MainSource</MainSource>')
    a('        </DelphiCompile>')
    for r in p.get("requires", []):
        a(f'        <DCCReference Include="{r}.dcp"/>')
    for u, f in p["units"]:
        a(f'        <DCCReference Include="{f}"/>')
    for u, f, form in p["forms"]:
        a(f'        <DCCReference Include="{f}">')
        a(f'            <Form>{form}</Form>')
        a(f'            <FormType>{"dfm" if p["framework"] == "VCL" else "fmx"}</FormType>')
        a('        </DCCReference>')
    a('        <BuildConfiguration Include="Base">')
    a('            <Key>Base</Key>')
    a('        </BuildConfiguration>')
    a('        <BuildConfiguration Include="Debug">')
    a('            <Key>Cfg_1</Key>')
    a('            <CfgParent>Base</CfgParent>')
    a('        </BuildConfiguration>')
    a('        <BuildConfiguration Include="Release">')
    a('            <Key>Cfg_2</Key>')
    a('            <CfgParent>Base</CfgParent>')
    a('        </BuildConfiguration>')
    a('    </ItemGroup>')
    a('    <ProjectExtensions>')
    a('        <Borland.Personality>Delphi.Personality.12</Borland.Personality>')
    a(f'        <Borland.ProjectType>{"Package" if is_pkg else "Application"}</Borland.ProjectType>')
    a('        <BorlandProject>')
    a('            <Delphi.Personality>')
    a('                <Source>')
    a(f'                    <Source Name="MainSource">{main}</Source>')
    a('                </Source>')
    # Project page: the IDE shows a README when the project opens - a demo's
    # own README.md next to its .dproj (Windows deployment), otherwise the
    # repository README
    if p["dir"].startswith("demos\\"):
        a('                <WelcomePageFile Path="README.md"/>')
    else:
        up = "..\\" * (p["dir"].count("\\") + 1)
        a(f'                <WelcomePageFile Path="{up}README.md"/>')
    a('            </Delphi.Personality>')
    if p.get("redist") or p.get("files"):
        # "files" are data next to the program: beside the library on desktop
        # platforms. Android would need assets\internal\ instead - not
        # supported here (no project ships files to Android yet).
        a('            <Deployment Version="5">')
        if p.get("skia"):
            skia_deploy(p, a)
        for pl in ("OSX64", "OSXARM64", "Linux64", "Android64"):
            if pl not in p["platforms"]:
                continue
            remote = REMOTE_DIR[pl]
            for cfg in ("Debug", "Release"):
                if p.get("redist"):
                    a(f'                <DeployFile LocalName="..\\..\\redistributable_bin\\{REDIST[pl]}{DLL[pl]}" Configuration="{cfg}" Class="File">')
                    a(f'                    <Platform Name="{pl}">')
                    a(f'                        <RemoteDir>{remote}</RemoteDir>')
                    a(f'                        <RemoteName>{DLL[pl]}</RemoteName>')
                    a('                        <Overwrite>true</Overwrite>')
                    a('                    </Platform>')
                    a('                </DeployFile>')
                # data files: beside the library, except where the project
                # names its own macOS data folder (mac_data)
                data_remote = p.get("mac_data", remote) if pl.startswith("OSX") else remote
                for f in p.get("files", []):
                    a(f'                <DeployFile LocalName="{f}" Configuration="{cfg}" Class="File">')
                    a(f'                    <Platform Name="{pl}">')
                    a(f'                        <RemoteDir>{data_remote}</RemoteDir>')
                    a(f'                        <RemoteName>{f.split(chr(92))[-1]}</RemoteName>')
                    a('                        <Overwrite>true</Overwrite>')
                    a('                    </Platform>')
                    a('                </DeployFile>')
                # Linux-only files (the ICU launcher script) beside the program
                for f in (p.get("linux_files", []) if pl == "Linux64" else []):
                    a(f'                <DeployFile LocalName="{f}" Configuration="{cfg}" Class="File">')
                    a(f'                    <Platform Name="{pl}">')
                    a(f'                        <RemoteDir>{remote}</RemoteDir>')
                    a(f'                        <RemoteName>{f.split(chr(92))[-1]}</RemoteName>')
                    a('                        <Overwrite>true</Overwrite>')
                    a('                    </Platform>')
                    a('                </DeployFile>')
        a('            </Deployment>')
    a('            <Platforms>')
    for pl in ALL_PLATFORMS:
        a(f'                <Platform value="{pl}">{"True" if pl in p["platforms"] else "False"}</Platform>')
    a('            </Platforms>')
    a('        </BorlandProject>')
    a('        <ProjectFileVersion>12</ProjectFileVersion>')
    a('    </ProjectExtensions>')
    a("    <Import Project=\"$(BDS)\\Bin\\CodeGear.Delphi.Targets\" Condition=\"Exists('$(BDS)\\Bin\\CodeGear.Delphi.Targets')\"/>")
    a("    <Import Project=\"$(APPDATA)\\Embarcadero\\$(BDSAPPDATABASEDIR)\\$(PRODUCTVERSION)\\UserTools.proj\" Condition=\"Exists('$(APPDATA)\\Embarcadero\\$(BDSAPPDATABASEDIR)\\$(PRODUCTVERSION)\\UserTools.proj')\"/>")
    a("    <Import Project=\"$(MSBuildProjectName).deployproj\" Condition=\"Exists('$(MSBuildProjectName).deployproj')\"/>")
    a('</Project>')
    with open(path, "wb") as fh:
        fh.write(b"\xef\xbb\xbf" + ("\r\n".join(L) + "\r\n").encode("utf-8"))
    return path


def dpk(p):
    path = os.path.join(ROOT, *p["dir"].split("\\"), p["name"] + ".dpk")
    L = [f"package {p['name']};", "",
         f"{{ {p['description']}. Generated by tools/gen_projects.py - edit the generator, not this file. }}", "",
         f"{{$DESCRIPTION '{p['description']}'}}",
         "{$RUNONLY}" if p["kind"] == "runtime" else "{$DESIGNONLY}",
         "{$IMPLICITBUILD ON}", "", "requires"]
    L += [f"  {r}{',' if i < len(p['requires']) - 1 else ';'}" for i, r in enumerate(p["requires"])]
    L += ["", "contains"]
    L += [f"  {u} in '{f}'{',' if i < len(p['units']) - 1 else ';'}" for i, (u, f) in enumerate(p["units"])]
    L += ["", "end."]
    with open(path, "w", newline="\r\n") as fh:
        fh.write("\n".join(L) + "\n")


def groupproj():
    path = os.path.join(ROOT, "Steamworks.groupproj")
    guid = existing_guid(path)
    L = ['<Project xmlns="http://schemas.microsoft.com/developer/msbuild/2003">',
         '    <PropertyGroup>', f'        <ProjectGuid>{guid}</ProjectGuid>', '    </PropertyGroup>',
         '    <ItemGroup>']
    # Shown in the Projects window (owner, 2026-10-30): applications first,
    # then runtime packages, then design packages. Build order is separate:
    # the Dependencies below (IDE) and the Build / Clean / Make targets
    # (MSBuild) build runtime packages, then design packages, then the
    # applications, which link the DCUs the runtime packages produce.
    rank_show = {"app": 0, "console": 0, "runtime": 1, "design": 2}
    rank_build = {"runtime": 0, "design": 1, "app": 2, "console": 2}
    # packages: framework-free, then FMX, then VCL; applications keep list order
    fw = lambda p: {"None": 0, "FMX": 1, "VCL": 2}.get(p["framework"], 3) \
        if p["kind"] in ("runtime", "design") else 0
    ordered = sorted(PROJECTS, key=lambda p: (rank_show[p["kind"]], fw(p)))
    build_order = sorted(PROJECTS, key=lambda p: (rank_build[p["kind"]], fw(p)))
    for p in ordered:
        rel = f"{p['dir']}\\{p['name']}.dproj"
        deps = ";".join(f"{q['dir']}\\{q['name']}.dproj" for q in PROJECTS if q["name"] in p.get("depends", []))
        L += [f'        <Projects Include="{rel}">',
              f'            <Dependencies>{deps}</Dependencies>' if deps else '            <Dependencies/>',
              '        </Projects>']
    L += ['    </ItemGroup>', '    <ProjectExtensions>',
          '        <Borland.Personality>Default.Personality.12</Borland.Personality>',
          '        <Borland.ProjectType/>', '        <BorlandProject>',
          '            <Default.Personality/>', '        </BorlandProject>', '    </ProjectExtensions>']
    for p in ordered:
        rel = f"{p['dir']}\\{p['name']}.dproj"
        n = p["name"]
        L += [f'    <Target Name="{n}">', f'        <MSBuild Projects="{rel}"/>', '    </Target>',
              f'    <Target Name="{n}:Clean">', f'        <MSBuild Projects="{rel}" Targets="Clean"/>', '    </Target>',
              f'    <Target Name="{n}:Make">', f'        <MSBuild Projects="{rel}" Targets="Make"/>', '    </Target>']
    names = [p["name"] for p in build_order]
    for t, suf in (("Build", ""), ("Clean", ":Clean"), ("Make", ":Make")):
        L += [f'    <Target Name="{t}">', f'        <CallTarget Targets="{";".join(n + suf for n in names)}"/>', '    </Target>']
    L += ["    <Import Project=\"$(BDS)\\Bin\\CodeGear.Group.Targets\" Condition=\"Exists('$(BDS)\\Bin\\CodeGear.Group.Targets')\"/>",
          '</Project>']
    with open(path, "wb") as fh:
        fh.write(b"\xef\xbb\xbf" + ("\r\n".join(L) + "\r\n").encode("utf-8"))


def lpi(p):
    """Writes the Lazarus project of p's Free Pascal twin (p["fpc_twin"]):
    the same units as the .dproj, plain FPC - no LCL, no package; the
    library is compiled from source through p["fpc_search"], units go to
    lib/<cpu>-<os>/, the program to <cpu>-<os>/ (both git-ignored)."""
    name = p["fpc_twin"]
    units = [f"{name}.lpr"] + [f.replace("\\", "/") for _, f in p["units"]]
    L = ['<?xml version="1.0" encoding="UTF-8"?>', '<CONFIG>', '  <ProjectOptions>', '    <Version Value="12"/>',
         '    <General>', '      <Flags>', '        <MainUnitHasCreateFormStatements Value="False"/>',
         '        <MainUnitHasTitleStatement Value="False"/>', '        <MainUnitHasScaledStatement Value="False"/>',
         '      </Flags>', '      <SessionStorage Value="InProjectDir"/>', f'      <Title Value="{name}"/>',
         '      <UseAppBundle Value="False"/>', '      <ResourceType Value="res"/>', '    </General>',
         '    <BuildModes>', '      <Item Name="Default" Default="True"/>', '    </BuildModes>',
         '    <PublishOptions>', '      <Version Value="2"/>', '    </PublishOptions>',
         '    <RunParams>', '      <FormatVersion Value="2"/>', '    </RunParams>', '    <Units>']
    for u in units:
        L += ['      <Unit>', f'        <Filename Value="{u}"/>', '        <IsPartOfProject Value="True"/>',
              '      </Unit>']
    L += ['    </Units>', '  </ProjectOptions>', '  <CompilerOptions>', '    <Version Value="11"/>',
          '    <Target>', f'      <Filename Value="$(TargetCPU)-$(TargetOS)/{name}"/>', '    </Target>',
          '    <SearchPaths>', '      <IncludeFiles Value="../../lib;$(ProjOutDir)"/>',
          f'      <OtherUnitFiles Value="{p["fpc_search"]}"/>',
          '      <UnitOutputDirectory Value="lib/$(TargetCPU)-$(TargetOS)"/>', '    </SearchPaths>',
          '    <Parsing>', '      <SyntaxOptions>', '        <SyntaxMode Value="Delphi"/>', '      </SyntaxOptions>',
          '    </Parsing>', '    <Linking>', '      <Debugging>', '        <DebugInfoType Value="dsDwarf3"/>',
          '      </Debugging>', '    </Linking>', '  </CompilerOptions>', '</CONFIG>']
    path = target(p, ".lpi", name)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(L) + "\n")
    return path


def target(p, ext, name=None):
    return os.path.join(ROOT, *p["dir"].split("\\"), (name or p["name"]) + ext)


